function main() {
  const rows = loadRows(readFileSync(CSV_PATH, "utf8"));
  const byCat = groupByCategory(rows);
  let blends = [];
  if (existsSync(BLENDS_PATH)) {
    blends = loadBlends(readFileSync(BLENDS_PATH, "utf8"));
    console.log(`[build] ${blends.length} competitor blends loaded`);
  }
  writeJson(rows, byCat);
  writeMarkdown(rows, byCat);
  writeHtml(rows, blends);
  const summary = FORMULARY_CATEGORIES.filter((c) => byCat[c].length)
    .map((c) => `${c}: ${byCat[c].length}`)
    .join(", ");
  console.log(`[build] ${rows.length} products — ${summary}`);
  console.log("[build] wrote formulary.json, FORMULARY.md, index.html");
}

main();
