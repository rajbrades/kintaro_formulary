// ==========================================================================
// KINTARO FORMULARY — Build Script (plain Node, zero dependencies)
// ==========================================================================
// Reads formulary.csv and emits three artifacts:
//   1. formulary.json  — the data, grouped and flat (for any consumer)
//   2. FORMULARY.md    — category-grouped markdown snapshot (diff-friendly)
//   3. index.html      — self-contained interactive viewer (open in a browser)
//
// Vocabulary + CSV parsing live in lib/vocab.mjs (single source of truth).
// Output is deterministic (no timestamps) so re-runs are byte-identical.
//
//   node scripts/build.mjs      (or: npm run build)

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

import { FORMULARY_CATEGORIES, PHARMACIES, loadRows, compareProducts } from "../lib/vocab.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CSV_PATH = join(ROOT, "formulary.csv");

