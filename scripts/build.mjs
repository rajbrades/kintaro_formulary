function groupByCategory(rows) {
  const out = {};
  for (const c of FORMULARY_CATEGORIES) out[c] = [];
  for (const r of rows) out[r.category].push(r);
  return out;
}

function writeJson(rows, byCat) {
  const counts = {};
  for (const c of FORMULARY_CATEGORIES) if (byCat[c].length) counts[c] = byCat[c].length;
  const out = { total: rows.length, counts, by_category: byCat, rows };
  writeFileSync(join(ROOT, "formulary.json"), JSON.stringify(out, null, 2) + "\n");
}

const mdEsc = (s) => String(s).replace(/\|/g, "\\|").replace(/\n/g, " ");

function writeMarkdown(rows, byCat) {
  const L = [];
  L.push("# Kintaro Formulary");
  L.push("");
  L.push("> GENERATED by `scripts/build.mjs` from `formulary.csv`. Do not edit by hand.");
  L.push("");
  L.push(`**${rows.length} products** across ${PHARMACIES.length} pharmacies.`);
  L.push("");
  L.push("## Summary");
  L.push("");
  L.push("| Category | Products |");
  L.push("|---|---:|");
  for (const c of FORMULARY_CATEGORIES) if (byCat[c].length) L.push(`| ${c} | ${byCat[c].length} |`);
  L.push(`| **Total** | **${rows.length}** |`);
  L.push("");
  const review = rows.filter((r) => r.tags.split("|").includes("review"));
  if (review.length) {
    L.push("## Flagged for review");
    L.push("");
    L.push("| Product | Strength | Category | Note |");
    L.push("|---|---|---|---|");
    for (const r of review) L.push(`| ${mdEsc(r.product_name)} | ${mdEsc(r.strength)} | ${r.category} | ${mdEsc(r.notes)} |`);
    L.push("");
  }
  for (const c of FORMULARY_CATEGORIES) {
    const rs = byCat[c];
    if (!rs.length) continue;
    L.push(`## ${c} (${rs.length})`);
    L.push("");
    L.push("| Product | Strength | Form | Package | Pharmacy | SKU | Wholesale | Tags | Notes |");
    L.push("|---|---|---|---|---|---|---:|---|---|");
    for (const r of rs) {
      const cost = r.wholesale_cost ? `$${r.wholesale_cost}` : "";
      L.push(
        `| ${mdEsc(r.product_name)} | ${mdEsc(r.strength)} | ${r.form} | ${mdEsc(r.package)} | ` +
          `${r.pharmacy} | ${mdEsc(r.sku)} | ${cost} | ${mdEsc(r.tags)} | ${mdEsc(r.notes)} |`
      );
    }
    L.push("");
  }
  writeFileSync(join(ROOT, "FORMULARY.md"), L.join("\n"));
}

